package ec.edu.uta.notificaciones;

import com.sun.net.httpserver.HttpExchange;
import com.sun.net.httpserver.HttpServer;
import java.io.IOException;
import java.net.InetSocketAddress;
import java.nio.charset.StandardCharsets;
import java.util.Objects;
import java.util.UUID;
import java.util.concurrent.atomic.AtomicInteger;
import javax.sql.DataSource;

import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;
import org.springframework.amqp.rabbit.listener.SimpleMessageListenerContainer;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.context.TestConfiguration;
import org.springframework.context.ApplicationContext;
import org.springframework.context.annotation.Bean;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.springframework.test.json.JsonCompareMode;
import org.springframework.test.web.servlet.MockMvc;

import static org.assertj.core.api.Assertions.assertThat;
import static org.hamcrest.Matchers.contains;
import static org.hamcrest.Matchers.containsString;
import static org.hamcrest.Matchers.not;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.head;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.content;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.header;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

@SpringBootTest(properties = {
    "app.consumidor-ventas.activo=false",
    "NOTIFICACIONES_DB_HOST=false",
    "spring.config.import=optional:classpath:sin-configuracion-local.properties",
    "spring.sql.init.mode=never"
})
@AutoConfigureMockMvc
class HistorialNotificacionesHttpTest {
    private static final String RUTA = "/api/notificaciones";
    private static final String CLAVE_PRUEBA = UUID.randomUUID().toString();
    private static final AtomicInteger CONSULTAS_IDENTIDAD = new AtomicInteger();
    private static HttpServer identidad;

    @Autowired
    private MockMvc mvc;
    @Autowired
    private DataSource origen;
    @Autowired
    private ApplicationContext contexto;

    @DynamicPropertySource
    static void configurar(DynamicPropertyRegistry variables) throws IOException {
        identidad = HttpServer.create(new InetSocketAddress("127.0.0.1", 0), 0);
        identidad.createContext("/api/identidad", HistorialNotificacionesHttpTest::responderIdentidad);
        identidad.start();
        variables.add("app.identidad-url", () -> "http://127.0.0.1:" + identidad.getAddress().getPort() + "/api/identidad");
        variables.add("app.notificacion-key", () -> CLAVE_PRUEBA);
    }

    @AfterAll
    static void cerrarIdentidad() {
        if (identidad != null) {
            identidad.stop(0);
        }
    }

    @TestConfiguration(proxyBeanMethods = false)
    static class BaseAislada {
        @Bean
        DataSource basePruebas() {
            return new DriverManagerDataSource("jdbc:h2:mem:" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1", "sa", "");
        }
    }

    @BeforeEach
    void prepararTabla() {
        jdbc().execute("DROP TABLE IF EXISTS notificaciones_ventas");
        jdbc().execute("""
            CREATE TABLE notificaciones_ventas (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                evento_id CHAR(36) NOT NULL UNIQUE,
                tipo VARCHAR(32) NOT NULL,
                venta_id INT NOT NULL,
                vehiculo_id INT NOT NULL,
                fecha_utc TIMESTAMP(6) NOT NULL
            )
            """);
        CONSULTAS_IDENTIDAD.set(0);
    }

    @Test
    void adminConsultaAvisoPersistidoEnUtcConSoloCuatroCampos() throws Exception {
        String evento = insertar(18, "VENTA_CONFIRMADA", "2026-11-20 05:56:53.000123");
        assertThat(contexto.getBeansOfType(SimpleMessageListenerContainer.class)).isEmpty();
        mvc.perform(get(RUTA).header("Authorization", "bearer admin-prueba"))
            .andExpect(status().isOk())
            .andExpect(header().string("Cache-Control", "no-store"))
            .andExpect(content().json("""
                [{"eventoId":"%s","ventaId":18,"fechaUTC":"2026-11-20T05:56:53.000123Z","estado":"CONFIRMADA"}]
                """.formatted(evento), JsonCompareMode.STRICT));
        assertThat(CONSULTAS_IDENTIDAD.get()).isOne();
    }

    @Test
    void historialVacioDevuelveColeccion() throws Exception {
        mvc.perform(get(RUTA).header("Authorization", "Bearer admin-prueba"))
            .andExpect(status().isOk())
            .andExpect(content().json("[]"));
    }

    @Test
    void consultaRepetidaEsEstableYNoModificaFilas() throws Exception {
        insertar(18, "VENTA_CONFIRMADA", "2026-11-20 05:56:52");
        insertar(19, "VENTA_CONFIRMADA", "2026-11-20 05:56:53");
        insertar(20, "VENTA_CONFIRMADA", "2026-11-20 05:56:53");
        insertar(21, "OTRO_TIPO", "2026-11-20 05:56:54");
        var antes = jdbc().queryForList("SELECT * FROM notificaciones_ventas ORDER BY id");
        for (int i = 0; i < 2; i++) {
            mvc.perform(get(RUTA).header("Authorization", "Bearer admin-prueba"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$[*].ventaId").value(contains(20, 19, 18)));
        }
        assertThat(jdbc().queryForList("SELECT * FROM notificaciones_ventas ORDER BY id")).isEqualTo(antes);
    }

    @Test
    void getSinBearerOConSoloClaveEsRechazadoSinConsultarIdentidad() throws Exception {
        mvc.perform(get(RUTA)).andExpect(status().isUnauthorized());
        mvc.perform(get(RUTA).header("X-Notification-Key", CLAVE_PRUEBA)).andExpect(status().isUnauthorized());
        mvc.perform(head(RUTA).header("X-Notification-Key", CLAVE_PRUEBA)).andExpect(status().isUnauthorized());
        assertThat(CONSULTAS_IDENTIDAD.get()).isZero();
    }

    @ParameterizedTest
    @ValueSource(strings = {"invalido-prueba", "expirado-prueba"})
    void identidadRechazaTokenInvalidoOVencido(String token) throws Exception {
        mvc.perform(get(RUTA).header("Authorization", "Bearer " + token))
            .andExpect(status().isUnauthorized());
        assertThat(CONSULTAS_IDENTIDAD.get()).isOne();
    }

    @Test
    void usuarioNoAdminNoPuedeSuplantarElRol() throws Exception {
        mvc.perform(get(RUTA).header("Authorization", "Bearer consulta-prueba").header("X-Role", "ROLE_ADMIN"))
            .andExpect(status().isForbidden());
    }

    @ParameterizedTest
    @ValueSource(strings = {"indisponible-prueba", "perfil-invalido-prueba", "redireccion-prueba"})
    void fallaCerradoSiIdentidadNoEmiteUnPerfilValido(String token) throws Exception {
        mvc.perform(get(RUTA).header("Authorization", "Bearer " + token))
            .andExpect(status().isServiceUnavailable());
        assertThat(CONSULTAS_IDENTIDAD.get()).isOne();
    }

    @Test
    void errorJdbcDevuelve503SinDetallesInternos() throws Exception {
        jdbc().execute("DROP TABLE notificaciones_ventas");
        mvc.perform(get(RUTA).header("Authorization", "Bearer admin-prueba"))
            .andExpect(status().isServiceUnavailable())
            .andExpect(content().string(not(containsString("notificaciones_ventas"))));
    }

    @Test
    void postRequiereClaveInclusoConBearerAdmin() throws Exception {
        mvc.perform(post(RUTA).header("Authorization", "Bearer admin-prueba"))
            .andExpect(status().isUnauthorized());
        mvc.perform(post(RUTA).header("X-Notification-Key", CLAVE_PRUEBA)
            .contentType("application/json").content("""
                {"vehiculoId":1,"destinatario":"p@example.test","tipo":"VENTA","mensaje":"prueba aislada"}
                """))
            .andExpect(status().isCreated());
        assertThat(CONSULTAS_IDENTIDAD.get()).isZero();
    }

    private JdbcTemplate jdbc() {
        return new JdbcTemplate(origen);
    }

    private String insertar(int venta, String tipo, String fecha) {
        String evento = UUID.randomUUID().toString();
        jdbc().update("""
            INSERT INTO notificaciones_ventas(evento_id, tipo, venta_id, vehiculo_id, fecha_utc)
            VALUES (?, ?, ?, 23, CAST(? AS TIMESTAMP))
            """, evento, tipo, venta, fecha);
        return evento;
    }

    private static void responderIdentidad(HttpExchange intercambio) throws IOException {
        try (intercambio) {
            CONSULTAS_IDENTIDAD.incrementAndGet();
            String token = intercambio.getRequestHeaders().getFirst("Authorization");
            String admin = "{\"usuario\":\"admin-prueba\",\"roles\":[\"ROLE_ADMIN\"],\"permisos\":[]}";
            int estado = 200;
            String cuerpo = admin;
            if (!"Bearer admin-prueba".equals(token)) {
                switch (Objects.toString(token, "")) {
                    case "Bearer consulta-prueba" ->
                        cuerpo = "{\"usuario\":\"consulta-prueba\",\"roles\":[\"ROLE_CONSULTA\"],\"permisos\":[]}";
                    case "Bearer perfil-invalido-prueba" ->
                        cuerpo = "{\"usuario\":\"admin-prueba\",\"roles\":[\"ROLE_ADMIN\", true]}";
                    case "Bearer redireccion-prueba" -> {
                        estado = 302;
                        intercambio.getResponseHeaders().set("Location", "/api/identidad");
                    }
                    case "Bearer indisponible-prueba" -> estado = 503;
                    default -> estado = 401;
                }
            }
            byte[] bytes = cuerpo.getBytes(StandardCharsets.UTF_8);
            intercambio.getResponseHeaders().set("Content-Type", "application/json");
            intercambio.sendResponseHeaders(estado, bytes.length);
            intercambio.getResponseBody().write(bytes);
        }
    }
}
